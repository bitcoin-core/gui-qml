#include <qml/models/chainmodel.h>

#include <QByteArray>
#include <QApplication>
#include <QString>

#include <cstddef>
#include <cstdint>

static int argc = 1;
static char arg0[] = "fuzz_chain_model";
static char* argv[] = {arg0, nullptr};
static QApplication app(argc, argv);

extern "C" int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size)
{
    const QByteArray raw(reinterpret_cast<const char*>(data), static_cast<int>(size));
    const QString network_name = QString::fromUtf8(raw);

    ChainModel model(network_name);
    (void)model.networkName();
    (void)model.assumedBlockchainSize();
    (void)model.assumedChainstateSize();
    return 0;
}
